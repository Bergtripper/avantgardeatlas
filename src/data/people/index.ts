export const peopleRegistry: Record<string, HistoricalFigure> = {};

ALL_PEOPLE.forEach((person) => {
  peopleRegistry[person.id] = person;
});

// Common alias mappings for frictionless resolution
peopleRegistry['kandinsky'] = wassilyKandinsky;
peopleRegistry['mies'] = miesVanDerRohe;
peopleRegistry['corbusier'] = leCorbusier;
peopleRegistry['figini-pollini'] = luigiFigini;
peopleRegistry['luigi-figini-gino-pollini'] = luigiFigini;

export const getPersonById = (id: string): HistoricalFigure | undefined => {
  if (!id) return undefined;
  return peopleRegistry[id] || ALL_PEOPLE.find((p) => p.id === id);
};
